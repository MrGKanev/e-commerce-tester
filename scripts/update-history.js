const footerHtml = '<p class="mt-10 text-center text-xs text-slate-600">Generated by <code class="rounded bg-slate-200 px-1.5 py-0.5">scripts/update-history.js</code> · <a class="text-blue-700 underline underline-offset-2" href="https://playwright.dev" target="_blank">Playwright</a></p>';
const pipClasses = { pass: 'bg-green-600', fail: 'bg-red-600', warn: 'bg-amber-500', neutral: 'bg-slate-400' };

const reportsDir = process.env.REPORTS_DIR || path.join(__dirname, '..', 'reports');

// ── Load site metadata from sites.json (for name / URL display) ──────────────

function loadSiteMeta() {
  const sitesFile = process.env.SITES_FILE || path.join(__dirname, '..', 'sites.json');
  if (!fs.existsSync(sitesFile)) return {};
  try {
    const arr = JSON.parse(fs.readFileSync(sitesFile, 'utf8'));
    const map = {};
    for (const s of arr) {
      if (s.slug) map[s.slug] = { name: s.name || s.slug, url: s.url || '' };
    }
    return map;
  } catch { return {}; }
}

// ── Collect all sites ────────────────────────────────────────────────────────

function collectAllSites() {
  const meta  = loadSiteMeta();
  const sites = [];

  if (!fs.existsSync(reportsDir)) return sites;

  for (const entry of fs.readdirSync(reportsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === '.trash') continue;
    // Skip dated dirs at the root (legacy single-site runs)
    if (/^\d{4}-\d{2}-\d{2}_\d{2}-\d{2}(?:-\d{2}-\d{3})?$/.test(entry.name)) continue;

    const slug     = entry.name;
    const siteDir  = path.join(reportsDir, slug);
    const runs     = collectRunsFromDir(siteDir, `${slug}/`);
    if (runs.length === 0) continue;

    runs.sort((a, b) => b.dir.localeCompare(a.dir));
    runs.forEach((run, index) => { run.changes = compareRuns(run, runs[index + 1]); });
    const latestMetadata = runs.reduce((latest, run) => !latest || run.dir > latest.dir ? run : latest, null)?.metadata.site || {};
    const m = meta[slug] || latestMetadata;
    sites.push({
      slug,
      name: m.name || formatName(slug),
      url:  m.url  || '',
      runs: runs.sort((a, b) => b.dir.localeCompare(a.dir)),
    });
  }

  const direct = collectRunsFromDir(reportsDir, '');
  direct.sort((a, b) => b.dir.localeCompare(a.dir));
  direct.forEach((run, index) => { run.changes = compareRuns(run, direct[index + 1]); });
  if (direct.length) sites.push({ slug: 'direct-runs', name: 'Direct runs (legacy)', url: '', runs: direct.sort((a, b) => b.dir.localeCompare(a.dir)) });
  return sites.sort((a, b) => a.name.localeCompare(b.name));
}

function readVitals(file) {
  if (!fs.existsSync(file)) return null;
  try {
    const result = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!Array.isArray(result.documents)) throw new Error('Invalid metrics document list');
    return result;
  } catch (error) { return { documents: [], error: error.message }; }
}

function renderVitals(run) {
  if (!run.vitals) return '';
  const documents = run.vitals.documents;
  const values = documents.flatMap(doc => Object.values(doc.metrics));
  const measured = values.filter(metric => metric.status === 'measured').length;
  return `<details><summary>Synthetic performance (${measured}/${values.length} measurements available)</summary>
    <p>Bounded observations from existing visits. Event latency is not field INP. Loading and ready-state timings may include injected pacing.</p>
    ${run.vitals.error ? `<p>${escHtml(run.vitals.error)}</p>` : ''}
    ${documents.map(doc => `<details><summary>${escHtml(doc.project || 'unknown browser')} · ${escHtml(doc.scenario || '')} · ${escHtml(doc.url)} · ${doc.window.durationMs} ms observed</summary>
      <p>Window: ${escHtml(doc.window.reason)} · paint ended: ${escHtml(doc.window.paintWindowEnded)} · ${doc.activeObservers} observers active at snapshot</p>
      ${(run.vitals.checks || []).filter(check => check.documentId === doc.id).map(check => `<p class="${check.assessment === 'within-budget' ? '' : 'text-amber-700'}">${escHtml(check.metric)}: ${escHtml(check.assessment)}</p>`).join('')}
      ${Object.entries(doc.metrics).map(([name, metric]) => `<p class="${metric.status === 'unmeasured' ? 'text-amber-700' : ''}">${escHtml(name)}: ${metric.status === 'measured' ? escHtml(metric.value) : 'Unmeasured — ' + escHtml(metric.reason)}</p>`).join('')}
      ${doc.actions.map(action => `<p>${escHtml(action.label)}: ${action.latency.status === 'measured' ? action.latency.value + ' ms event latency' : 'Unmeasured — ' + escHtml(action.latency.reason)} · operation ${escHtml(action.outcome)} · ready-state ${escHtml(action.readyElapsedMs)} ms</p>`).join('')}
      <pre>${escHtml(JSON.stringify(doc.entries, null, 2))}</pre>
    </details>`).join('')}
  </details>`;
}

function readSpelling(file) {
  if (!fs.existsSync(file)) return null;
  try {
    const report = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!report || !Array.isArray(report.findings)) throw new Error('Invalid spelling report');
    return report;
  } catch (error) { return { findings: [], unsupportedLanguages: [], error: error.message }; }
}
function readCommerce(file) {
  if (!fs.existsSync(file)) return null;
  try {
    const report = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!Array.isArray(report.checks) || report.checks.some(check => !check || typeof check !== 'object' || !Array.isArray(check.observations)))
      throw new Error('Invalid commerce checks');
    return report;
  } catch (error) { return { checks: [], error: error.message }; }
}
function renderCommerce(run) {
  if (!run.commerce) return '';
  const checks = run.commerce.checks;
  return `<details><summary>Public storefront price and availability (${checks.length} checks)</summary>
    <p>Variant-specific observations from the storefront and the same visitor session. Unverified evidence is not a successful comparison.</p>
    ${run.commerce.error ? `<p>${escHtml(run.commerce.error)}</p>` : ''}
    ${checks.map(check => `<details><summary>${escHtml(check.productHandle)} · ${escHtml(check.kind)} · ${escHtml(check.project)} · ${escHtml(check.status)}</summary>
      ${check.reason ? `<p>${escHtml(check.reason)}</p>` : ''}<pre>${escHtml(JSON.stringify(check.observations, null, 2))}</pre></details>`).join('')}
  </details>`;
}

function readJourneys(file) {
  if (!fs.existsSync(file)) return null;
  try {
    const report = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!Array.isArray(report.checks) || report.checks.some(check => !check || !Array.isArray(check.steps) || check.steps.some(step => !step || typeof step !== 'object'))) throw new Error('Invalid buyer journey report');
    return report;
  } catch (error) { return { checks: [], error: error.message }; }
}
function renderJourneys(run) {
  if (!run.journeys) return '';
  return '<details><summary>Buyer journey (' + run.journeys.checks.length + ' checks)</summary><p>Search → product → variant → add → quantity → checkout. No order submitted. Unverified steps remain incomplete.</p>' +
    (run.journeys.error ? '<p>' + escHtml(run.journeys.error) + '</p>' : '') +
    run.journeys.checks.map(check => '<details><summary>' + escHtml(check.platform) + (check.market ? ' · ' + escHtml(check.market) : '') + ' · ' + escHtml(check.project) + ' · ' + escHtml(check.status) + (check.failedStep ? ' · step: ' + escHtml(check.failedStep) : '') + '</summary>' + (check.reason ? '<p>' + escHtml(check.reason) + '</p>' : '') + '<table><thead><tr><th>Step</th><th>Status</th><th>Expected</th><th>Observed</th></tr></thead><tbody>' + check.steps.map(step => '<tr><td>' + escHtml(step.name) + '</td><td>' + escHtml(step.status) + '</td><td><pre>' + escHtml(JSON.stringify(step.expected, null, 2) || '') + '</pre></td><td><pre>' + escHtml(JSON.stringify(step.actual, null, 2) || step.reason || '') + '</pre></td></tr>').join('') + '</tbody></table></details>').join('') + '</details>';
}

function collectRunsFromDir(dir, relPrefix) {
  if (!fs.existsSync(dir)) return [];

  return fs.readdirSync(dir)
    .filter(d => /^\d{4}-\d{2}-\d{2}_\d{2}-\d{2}(?:-\d{2}-\d{3})?$/.test(d))
    .map(d => {
      const runDir = path.join(dir, d);
      const metadataPath = path.join(runDir, 'run-metadata.json');
      const resultsPath = path.join(runDir, 'results.json');
      let results = {}, metadata = {}, issue = null;
      try {
        if (fs.existsSync(metadataPath)) {
          metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
          if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) throw new Error('Expected a metadata object');
        }
      } catch (error) { metadata = {}; issue = `Unreadable metadata: ${error.message}`; }
      try {
        if (fs.existsSync(resultsPath)) {
          results = JSON.parse(fs.readFileSync(resultsPath, 'utf8'));
          if (!results || typeof results !== 'object' || Array.isArray(results) || (results.suites && !Array.isArray(results.suites))) throw new Error('Expected a results object with a suite array');
        }
        else issue = 'Final results.json is missing; execution has no final report';
      } catch (error) { results = {}; issue = `Unreadable results.json: ${error.message}`; }
      const htmlRelative = fs.existsSync(path.join(runDir, 'html', 'index.html')) ? 'html/index.html' :
        fs.existsSync(path.join(runDir, 'index.html')) ? 'index.html' : null;
      const prefix = './' + [...relPrefix.split('/').filter(Boolean), d].map(encodeURIComponent).join('/') + '/';
      return {
        ...summarizeRun(results, metadata, issue),
        vitals: readVitals(path.join(runDir, 'web-vitals.json')),
        spelling: readSpelling(path.join(runDir, 'spelling.json')),
        commerce: readCommerce(path.join(runDir, 'commerce-consistency.json')),
        journeys: readJourneys(path.join(runDir, 'buyer-journeys.json')),
        artifactLink: file => {
          let target = path.isAbsolute(file) ? file : path.resolve(runDir, file);
          if (!fs.existsSync(target) && results.config?.projects?.[0]?.outputDir) target = path.resolve(runDir, path.relative(path.dirname(results.config.projects[0].outputDir), file));
          const relative = path.relative(reportsDir, target);
          return !relative.startsWith('..') && !path.isAbsolute(relative) && fs.existsSync(target) ? './' + relative.split(path.sep).map(encodeURIComponent).join('/') : null;
        },
        dir: d, date: formatDate(d),
        reportLink: htmlRelative ? prefix + htmlRelative : null,
        metadataLink: fs.existsSync(metadataPath) ? prefix + 'run-metadata.json' : null,
        resultsLink: fs.existsSync(resultsPath) ? prefix + 'results.json' : null,
      };
    })
    .filter(Boolean);
}

// ── Main ─────────────────────────────────────────────────────────────────────

const sites    = collectAllSites();
const generated = new Date().toLocaleString('bg-BG', { timeZone: 'Europe/Sofia' });

const html = buildDashboard(sites, generated);
fs.mkdirSync(reportsDir, { recursive: true });
fs.writeFileSync(path.join(reportsDir, 'dashboard.html'), html, 'utf8');
console.log(`✓ Dashboard updated → reports/dashboard.html (${sites.length} site${sites.length !== 1 ? 's' : ''})`);

// ── HTML builder ─────────────────────────────────────────────────────────────

// Reports open as plain files, so the compiled Tailwind stylesheet is inlined (run `pnpm build:css`).
function tailwindCss() {
  const file = process.env.TAILWIND_CSS || path.join(__dirname, '..', 'web', 'tailwind.css');
  try { return fs.readFileSync(file, 'utf8').replace(/<\/style/gi, '<\\/style'); }
  catch { console.warn(`! ${file} not found; run "pnpm build:css" for a styled dashboard`); return ''; }
}

function buildDashboard(sites, generated) {
  const statuses = sites.map(site => site.runs[0]?.status);
  const dot = statuses.some(status => ['failed', 'global-errors'].includes(status)) ? pipClasses.fail :
    statuses.length && statuses.every(status => status === 'passed') ? pipClasses.pass :
    statuses.some(status => ['flaky', 'interrupted', 'incomplete'].includes(status)) ? pipClasses.warn : pipClasses.neutral;

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Store Health Dashboard</title>
  <style>${tailwindCss()}</style>
</head>
<body class="min-h-screen bg-slate-50 text-base text-slate-900 antialiased">

<header class="border-b border-slate-200 bg-white">
  <div class="mx-auto flex max-w-6xl flex-wrap items-center justify-between gap-x-6 gap-y-1 px-4 py-3 sm:px-6 lg:px-8">
    <h1 class="flex items-center gap-2.5 text-base font-bold tracking-tight">
      <span class="size-2.5 shrink-0 rounded-full ${dot}" aria-hidden="true"></span>
      Store Health Dashboard
    </h1>
    <p class="text-xs text-slate-600">Generated: ${generated}</p>
  </div>
  <nav class="mx-auto flex max-w-6xl overflow-x-auto px-2 sm:px-4 lg:px-6" aria-label="Sites">
  <button class="${tabClass}" data-tab="all" aria-current="true" onclick="showTab('all')">
    All Sites
    <span class="rounded-full bg-blue-100 px-2 py-0.5 text-xs font-semibold text-blue-800">${sites.length}</span>
  </button>
  ${sites.map(s => {
    const pip = pipClasses[statusInfo(s.runs[0])[1]];
    return `<button class="${tabClass}" data-tab="${escHtml(s.slug)}" aria-current="false" onclick="showTab(this.dataset.tab)">
    <span class="size-2 shrink-0 rounded-full ${pip}" aria-hidden="true"></span>${escHtml(s.name)}
  </button>`;
  }).join('\n  ')}
  </nav>
</header>

<main>
<!-- ══ All Sites tab ═══════════════════════════════════════════════════════ -->
<div id="tab-all">
  <div class="${pageClass}">
    ${sites.length === 0 ? `
    <div class="px-6 py-16 text-center text-slate-600">
      <strong class="text-slate-900">No runs yet</strong>
      <p class="mt-2 text-sm">Run <code class="rounded bg-slate-200 px-1.5 py-0.5">pnpm test</code> to get started, then check back here.</p>
    </div>` : `
    ${buildOverviewCards(sites)}
    <h2 class="${sectionLabelClass}">Sites</h2>
    <div class="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
      ${sites.map(s => buildSiteCard(s)).join('\n      ')}
    </div>`}
    ${footerHtml}
  </div>
</div>

<!-- ══ Per-site tabs ════════════════════════════════════════════════════════ -->
${sites.map(s => `
<div id="tab-${escHtml(s.slug)}" hidden>
  <div class="${pageClass}">
    ${buildSitePanel(s)}
    ${footerHtml}
  </div>
</div>`).join('')}
</main>

<script>
  function showTab(id) {
    document.querySelectorAll('[data-tab]').forEach(b => { if (b.tagName === 'BUTTON') b.setAttribute('aria-current', String(b.dataset.tab === id)); });
    document.querySelectorAll('main > div').forEach(p => { p.hidden = p.id !== 'tab-' + id; });
  }
</script>

</body>
</html>`;
}

// ── Overview panel (All Sites tab) ───────────────────────────────────────────

function statusInfo(run) {
  return {
    passed: ['Passed', 'pass'], failed: ['Failed', 'fail'], flaky: ['Flaky', 'warn'],
    empty: ['No tests', 'neutral'], interrupted: ['Interrupted', 'warn'],
    'global-errors': ['Global errors', 'fail'], incomplete: ['Incomplete', 'warn'],
    'not-applicable': ['No applicable tests', 'neutral'],
  }[run?.status] || ['Unknown', 'neutral'];
}

function statusBadge(run) {
  const [label, color] = statusInfo(run);
  const tone = { pass: 'bg-green-100 text-green-800', fail: 'bg-red-100 text-red-800', warn: 'bg-amber-100 text-amber-900', neutral: 'bg-slate-100 text-slate-700' }[color];
  return `<span class="inline-flex items-center gap-1.5 rounded-full px-2.5 py-0.5 text-xs font-semibold whitespace-nowrap ${tone}"><span class="size-1.5 rounded-full ${pipClasses[color]}"></span>${label}</span>`;
}

function metricValue(value) { return value === null ? '—' : `${value}%`; }

function metricCard(value, label, detail) {
  return `<div class="${cardClass}"><div class="text-3xl leading-none font-bold tracking-tight text-blue-700">${escHtml(value)}</div><div class="mt-2 text-xs font-semibold tracking-wide text-slate-700 uppercase">${label}</div><div class="mt-2 text-xs text-slate-600">${detail}</div></div>`;
}

function buildOverviewCards(sites) {
  const last = sites.map(s => s.runs[0]).filter(Boolean);
  const executed = last.reduce((sum, run) => sum + run.executed, 0);
  const applicable = last.reduce((sum, run) => sum + run.applicable, 0);
  const successful = last.reduce((sum, run) => sum + run.passed + run.flaky, 0);
  return `<h2 class="${sectionLabelClass}">Latest runs</h2><div class="mb-8 grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
    ${metricCard(sites.length, 'Sites', `${sites.reduce((sum, site) => sum + site.runs.length, 0)} total runs`)}
    ${metricCard(last.filter(r => r.allPassed).length + ' / ' + sites.length, 'Clean runs', 'No failures, flaky tests, global errors or uncovered applicable tests')}
    ${metricCard(metricValue(percent(successful, executed)), 'Executed pass rate', `${successful} successful final outcomes / ${executed} completed tests`)}
    ${metricCard(metricValue(percent(executed, applicable)), 'Applicable coverage', `${executed} completed / ${applicable} applicable selected tests`)}
  </div>`;
}

function buildSiteCard(site) {
  const last = site.runs[0];
  const stat = (value, label) => `<div class="flex flex-col gap-0.5"><span class="text-sm font-semibold">${value}</span><span class="text-xs tracking-wide text-slate-600 uppercase">${label}</span></div>`;
  return `<button type="button" class="${cardClass} cursor-pointer text-left transition-shadow hover:shadow-md focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-blue-600" data-tab="${escHtml(site.slug)}" onclick="showTab(this.dataset.tab)">
    <div class="flex items-center justify-between gap-3"><span class="font-semibold break-words">${escHtml(site.name)}</span>${statusBadge(last)}</div>
    ${site.url ? `<div class="mt-1 truncate text-xs text-slate-600">${escHtml(site.url)}</div>` : ''}
    ${last.spelling ? `<p class="mt-2 text-xs text-amber-700">${last.spelling.error ? 'Spelling report unavailable' : 'Spelling review: ' + last.spelling.findings.filter(f => !f.accepted).length + ' · unchecked languages: ' + (last.spelling.unsupportedLanguages || []).length}</p>` : ''}
    <div class="mt-4 grid grid-cols-3 gap-3">
      ${stat(metricValue(last.passRate), 'Executed pass rate')}
      ${stat(metricValue(last.coverage), 'Applicable coverage')}
      ${stat(site.runs.length, 'Runs')}
    </div>
  </button>`;
}

function renderMetadata(run) {
  const metadata = run.metadata;
  const projects = metadata.projects || [];
  return `<details><summary>Run metadata</summary>
    ${metadata.versions ? `<p>Versions: project ${escHtml(metadata.versions.project ?? 'unknown')} · Playwright ${escHtml(metadata.versions.playwright ?? 'unknown')} · Node ${escHtml(metadata.versions.node ?? 'unknown')}</p>` : '<p>Versions not recorded in this legacy run.</p>'}
    ${projects.map(project => `<p>${escHtml(project.name)}: ${escHtml(project.browser)} ${escHtml(metadata.browserVersions?.[project.name] || '(version not observed)')} · locale ${escHtml(project.locale)} · timezone ${escHtml(project.timezone || 'default')} · retries ${escHtml(project.retries)} · repeat ${escHtml(project.repeatEach)}</p>`).join('')}
    ${metadata.configuration ? `<p>Site configuration:</p><pre>${escHtml(JSON.stringify(metadata.configuration, null, 2))}</pre>` : ''}
    ${metadata.source ? `<p>Source: ${escHtml(metadata.source.commit || 'unknown')} · working tree ${typeof metadata.source.dirty !== 'boolean' ? 'unknown' : metadata.source.dirty ? 'modified' : 'clean'}</p>` : ''}
    ${metadata.selection ? `<p>Selection and tags:</p><pre>${escHtml(JSON.stringify(metadata.selection, null, 2))}</pre>` : '<p>Selection/tags were not recorded.</p>'}
    ${metadata.site ? `<p>Site: ${escHtml(metadata.site.name)} · ${escHtml(metadata.site.url)}</p>` : ''}
    <p>${escHtml(metadata.phase || 'Legacy final JSON')} · status ${escHtml(metadata.status || 'not recorded')} · exit ${escHtml(metadata.exitCode ?? 'not recorded')}${metadata.signal ? ` · signal ${escHtml(metadata.signal)}` : ''}</p>
    ${metadata.pacing ? `<p>Request pacing:</p><pre>${escHtml(JSON.stringify(metadata.pacing, null, 2))}</pre>` : ''}
    ${run.metadataLink ? `<a href="${run.metadataLink}" target="_blank">Metadata JSON →</a>` : ''}
  </details>`;
}

function renderDiagnostics(run) {
  const relevant = run.scenarios.filter(s => s.outcome !== 'passed');
  return `${renderJourneys(run)}${renderCommerce(run)}${renderVitals(run)}${!run.scopeKnown ? '<p>Scenario inventory was not recorded; selected scope is unknown.</p>' : run.total === 0 ? '<p>No tests selected or discovered.</p>' : ''}
    ${run.reportIssue ? `<p class="text-amber-700">${escHtml(run.reportIssue)}</p>` : ''}
    ${run.globalErrors.length ? `<details><summary>Global errors (${run.globalErrors.length})</summary>${run.globalErrors.map(error => `<pre>${escHtml(error)}</pre>`).join('')}</details>` : ''}
    <details><summary>Scenarios (${relevant.length} need attention / ${run.total} selected)</summary>
      ${relevant.length ? relevant.map(scenario => `<details class="my-2 border-l-2 border-slate-200 p-2">
        <summary>${escHtml(scenario.title)} · ${escHtml(scenario.project)} · ${escHtml(scenario.outcome)}${scenario.change ? ' · ' + scenario.change : ''}${scenario.notApplicable ? ' · not applicable' : ''}</summary>
        <p>${escHtml(scenario.file)}${scenario.line ? ':' + scenario.line : ''}${scenario.tags?.length ? ' · ' + escHtml(scenario.tags.join(' ')) : ''}</p>
        ${(scenario.urls || []).map(url => `<p>URL: ${escHtml(url)}</p>`).join('')}
        ${(scenario.artifacts || []).map(artifact => { const href = run.artifactLink(artifact.path); return href ? `<p><a href="${href}" target="_blank">${escHtml(artifact.name === 'trace' ? 'Trace ZIP' : artifact.name === 'commerce-consistency.json' ? 'Price and availability evidence' : 'Screenshot: ' + artifact.name)} →</a></p>` : ''; }).join('')}
        ${(scenario.reasons || []).map(reason => `<p>${escHtml(reason)}</p>`).join('')}
        ${['not-run', 'interrupted', 'unfinished'].includes(scenario.outcome) ? '<p>Execution did not complete; this test remains in the coverage denominator.</p>' : ''}
        ${scenario.activeRetry !== undefined ? `<p>Was active at last checkpoint: attempt ${scenario.activeRetry + 1}</p>` : ''}
        ${(scenario.attempts || []).map(attempt => `<p>Attempt ${attempt.retry + 1}: ${escHtml(attempt.status)}</p>${attempt.errors.map(error => `<pre>${escHtml(error)}</pre>`).join('')}`).join('')}
      </details>`).join('') : '<p>No per-scenario diagnostics recorded.</p>'}
    </details>${run.spelling ? `<details><summary>Spelling (${run.spelling.findings.length} unique findings)</summary>${run.spelling.error ? `<p class="text-red-700">Spelling report unreadable: ${escHtml(run.spelling.error)}</p>` : ''}${run.spelling.findings.map(finding => `<p><strong>${escHtml(finding.word)}</strong> · ${escHtml(finding.language)} · ${escHtml(finding.component)} · ${escHtml((finding.sources || [finding.source]).join(', '))}${finding.accepted ? ' · accepted' : ''}</p><p>${escHtml(finding.text)}</p><p>${escHtml(finding.urls.join(', '))}</p>${run.scenarios.flatMap(s => (s.artifacts || []).filter(artifact => finding.locations.some(location => location.screenshot === artifact.name)).map(artifact => { const href = run.artifactLink(artifact.path); return href ? `<p><a href="${href}" target="_blank">${escHtml(s.project)} · ${escHtml(s.name || s.title)} · spelling screenshot →</a></p>` : ''; })).join('')}<p>Suggestions: ${escHtml(finding.suggestions.join(', '))}</p><pre>${escHtml(JSON.stringify(finding.locations, null, 2))}</pre>`).join('')}${run.spelling.ocr?.enabled === false ? '<p>OCR disabled</p>' : run.spelling.ocr ? `<p>OCR: ${run.spelling.ocr.imagesChecked} images · ${run.spelling.ocr.wordsRecognized} recognized words · ${run.spelling.ocr.lowConfidenceSkipped} low-confidence words awaiting review · ${escHtml((run.spelling.ocr.engines || []).join(', '))}</p>` : ''}<p>Unchecked languages: ${escHtml((run.spelling.unsupportedLanguages || []).join(', ') || 'none')}</p></details>` : ''}${renderMetadata(run)}`;
}

function buildTrend(runs, metric, label) {
  const recent = runs.slice(0, 20).reverse();
  return `<div class="mb-6 overflow-x-auto ${cardClass}"><div class="mb-2.5 text-xs text-slate-600">${label} · latest ${recent.length} runs</div><div class="flex h-14 items-end gap-1.5">
    ${recent.map(run => {
      const height = Math.max(4, Math.round((run[metric] || 0) * 0.52));
      return `<div class="w-6 shrink-0 rounded-t ${pipClasses[statusInfo(run)[1]]}" style="height:${height}px" title="${run.date} · ${metricValue(run[metric])} · ${statusInfo(run)[0]}"></div>`;
    }).join('')}
    </div><div class="mt-1.5 flex gap-1.5 border-t border-slate-200 pt-1.5">${recent.map(run => `<div class="w-6 shrink-0 overflow-hidden text-center text-[0.6rem] whitespace-nowrap text-slate-600">${run.date.slice(0, 5)}</div>`).join('')}</div></div>`;
}

