/**
 * update-history.js
 * Scans reports/{site-slug}/{date}/ directories, reads results.json from each,
 * and regenerates reports/dashboard.html with a tabbed multi-site summary.
 *
 * Report structure:
 *   reports/
 *   ├── dashboard.html
 *   ├── {slug}/
 *   │   └── {date}/
 *   │       ├── index.html
 *   │       └── results.json
 *   └── ...
 */

const fs   = require('fs');
const path = require('path');
const { summarizeRun, percent, compareRuns } = require('./report-model');

const pageClass = 'mx-auto max-w-6xl px-4 py-6 sm:px-6 sm:py-8 lg:px-8';
const sectionLabelClass = 'mb-3 text-xs font-semibold tracking-wider text-slate-600 uppercase';
const cardClass = 'rounded-xl border border-slate-200 bg-white p-5 shadow-sm';
// Diagnostic markup uses plain tags; these arbitrary variants style them without custom selectors.
const diagnosticsClass = 'text-xs [&_a]:font-medium [&_a]:text-blue-700 [&_a:hover]:underline [&_details]:mt-1 [&_details_p]:my-1.5 [&_details_p]:break-words [&_pre]:my-2 [&_pre]:max-h-64 [&_pre]:overflow-auto [&_pre]:rounded [&_pre]:bg-slate-100 [&_pre]:p-2.5 [&_pre]:break-words [&_pre]:whitespace-pre-wrap [&_summary]:cursor-pointer [&_summary]:py-0.5 [&_summary]:font-medium [&_summary]:text-slate-700 [&_table]:my-2 [&_table]:w-full [&_td]:py-1 [&_td]:pr-3 [&_td]:align-top [&_th]:pr-3 [&_th]:text-left [&_th]:font-semibold [&_th]:text-slate-700';

